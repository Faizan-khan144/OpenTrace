export const categoryById = Object.fromEntries(categories.map((c) => [c.id, c]))

export function getCategory(id) {
  return categoryById[id] || null
}

export function getSubcategory(category, subId) {
  if (!category) return null
  return category.subcategories.find((s) => s.id === subId) || null
}

export function subcategoryLabel(categoryId, subId) {
  const cat = getCategory(categoryId)
  const sub = cat ? cat.subcategories.find((s) => s.id === subId) : null
  return sub ? sub.name : (subId || '')
}